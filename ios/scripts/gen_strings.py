#!/usr/bin/env python3
"""Regenerates ios/Mynine/Core/StringsTable.swift from the Android string resources, so both apps say the same thing.

Run from the repo root: python3 ios/scripts/gen_strings.py
iOS-only strings live in EXTRA below.
"""
import re

BASE = 'android/app/src/main/res/'
EXTRA = {
    'apple_failed': ("Apple orqali kirib bo'lmadi.", "Не удалось войти через Apple.", "Couldn't sign in with Apple."),
    'decode_failed': ("Javobni o'qib bo'lmadi.", "Не удалось прочитать ответ.", "Couldn't read the response."),
    'ins_r3_ios': ("Matnni belgilab Highlight yoki Note qo'shing.", "Выделите текст, чтобы добавить Highlight или Note.", "Select text to add a Highlight or a Note."),
}


def load(path):
    out = {}
    for key, value in re.findall(r'<string name="([^"]+)">(.*?)</string>', open(path).read(), re.S):
        out[key] = value.replace("\\'", "'").replace('\\"', '"').replace('\\n', '\n').replace('&lt;', '<').replace('&amp;', '&')
    return out


def swift(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


uz, ru, en = load(BASE + 'values/strings.xml'), load(BASE + 'values-ru/strings.xml'), load(BASE + 'values-en/strings.xml')
uz.pop('app_name', None)
lines = [
    '// Generated by ios/scripts/gen_strings.py from the Android string resources (android/app/src/main/res/values*/strings.xml).',
    '// Do not edit by hand: change the Android strings (or EXTRA in the script) and run it again.',
    '',
    'let stringsTable: [String: (uz: String, ru: String, en: String)] = [',
]
for key in uz:
    lines.append('    %s: (%s, %s, %s),' % (swift(key), swift(uz[key]), swift(ru.get(key, uz[key])), swift(en.get(key, uz[key]))))
for key, (a, b, c) in EXTRA.items():
    lines.append('    %s: (%s, %s, %s),' % (swift(key), swift(a), swift(b), swift(c)))
lines.append(']')
open('ios/Mynine/Core/StringsTable.swift', 'w').write('\n'.join(lines) + '\n')
print(len(uz) + len(EXTRA), 'strings')
